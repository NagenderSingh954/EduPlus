import { Queue, Worker, Job } from 'bullmq';
import IORedis from 'ioredis';
import { prisma } from '../lib/prisma.js';
import { NotificationType, Priority, TaskCategory, TaskSource } from '@prisma/client';

const redisUrl = process.env.REDIS_URL || 'redis://localhost:6379';

let connection: IORedis | null = null;
let dailyPlanQueue: Queue | null = null;
let dailyPlanWorker: Worker | null = null;

try {
  connection = new IORedis(redisUrl, {
    maxRetriesPerRequest: null,
    enableReadyCheck: false,
    lazyConnect: true,
    retryStrategy: () => null // don't infinitely retry if redis isn't running
  });

  connection.on('error', (err) => {
    // Gracefully handle redis offline event
  });

  connection.connect().then(() => {
    console.log('⚡ Redis connected for BullMQ queues.');

    // Initialize BullMQ Queue
    dailyPlanQueue = new Queue('daily-academic-plan', { connection: connection! });

    // Initialize Worker
    dailyPlanWorker = new Worker(
      'daily-academic-plan',
      async (job: Job) => {
        console.log(`📋 [BullMQ Worker] Processing daily plan job ${job.id} for student:`, job.data.studentProfileId);
        await executeDailyPlanGeneration(job.data.studentProfileId);
      },
      { connection: connection! }
    );

    dailyPlanWorker.on('completed', job => {
      console.log(`✅ [BullMQ Worker] Job ${job.id} completed successfully.`);
    });

    dailyPlanWorker.on('failed', (job, err) => {
      console.warn(`⚠️ [BullMQ Worker] Job ${job?.id} failed:`, err);
    });
  }).catch(err => {
    console.log('ℹ️ Redis not detected on localhost:6379 — running BullMQ in resilient in-process mode.');
  });
} catch (e: any) {
  console.log('ℹ️ Redis offline, running in resilient in-process mode.');
}

// Core execution logic for daily plans
export async function executeDailyPlanGeneration(studentProfileId?: string) {
  try {
    const students = studentProfileId
      ? await prisma.studentProfile.findMany({ where: { id: studentProfileId }, include: { user: true } })
      : await prisma.studentProfile.findMany({ include: { user: true } });

    for (const student of students) {
      // Find today's classes
      const enrollments = await prisma.enrollment.findMany({
        where: { studentId: student.id },
        select: { courseId: true }
      });
      const courseIds = enrollments.map(e => e.courseId);

      const days = ['SUNDAY', 'MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY'];
      const day = days[new Date().getDay()];

      const todayClasses = await prisma.timetableEntry.findMany({
        where: { courseId: { in: courseIds }, dayOfWeek: day },
        include: { course: true }
      });

      // Find upcoming assignments
      const upcomingAssignment = await prisma.assignment.findFirst({
        where: {
          courseId: { in: courseIds },
          dueDate: { gte: new Date() },
          submissions: { none: { studentId: student.id } }
        },
        include: { course: true },
        orderBy: { dueDate: 'asc' }
      });

      // Create a curated Daily Plan Task
      const taskTitle = upcomingAssignment
        ? `Daily Priority: Review ${upcomingAssignment.course.code} & prep Assignment`
        : `Daily Priority: Review lecture notes for ${todayClasses[0]?.course.name || 'Core Subjects'}`;

      await prisma.task.create({
        data: {
          studentId: student.id,
          title: taskTitle,
          description: `Auto-generated by AcademiQ Daily Academic Scheduler based on your timetable and deadlines.`,
          category: TaskCategory.STUDY,
          priority: Priority.HIGH,
          estimatedMinutes: 45,
          source: TaskSource.DAILY_PLAN
        }
      });

      // Create Notification
      await prisma.notification.create({
        data: {
          userId: student.userId,
          title: '🌅 Your Daily Academic Plan is Ready',
          message: `Today you have ${todayClasses.length} lectures scheduled. Top focus: ${taskTitle}.`,
          type: NotificationType.DAILY_PLAN,
          actionUrl: '/dashboard'
        }
      });
    }

    return { success: true, processedStudents: students.length };
  } catch (err) {
    console.error('Error generating daily plans:', err);
    throw err;
  }
}

// Dispatch job
export async function scheduleDailyPlanJob(studentProfileId?: string) {
  if (dailyPlanQueue) {
    await dailyPlanQueue.add('generate-plan', { studentProfileId, timestamp: Date.now() });
    return { queued: true, provider: 'BullMQ' };
  } else {
    // Fallback in-process execution
    const result = await executeDailyPlanGeneration(studentProfileId);
    return { queued: false, provider: 'In-Process', result };
  }
}
